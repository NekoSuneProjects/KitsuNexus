'use strict'
const test = require('node:test')
const assert = require('node:assert/strict')
const { ActivityEvents } = require('../modules/vrchat/world/activityEvents')
test('activity preserves joins and leaves within a single poll and suppresses duplicate joins', () => {
  const a = new ActivityEvents()
  a.process('[Behaviour] OnPlayerJoined Test User (usr_test)')
  a.process('[Behaviour] OnPlayerJoined Test User (usr_test)')
  a.process('[Behaviour] OnPlayerLeft Test User (usr_test)')
  assert.deepEqual(a.snapshot().map(e => [e.kind, e.name]), [['join', 'Test User'], ['leave', 'Test User']])
})
test('activity detects explicit avatar loads and switches without treating loading as a switch', () => {
  const a = new ActivityEvents()
  a.process('[Behaviour] Loading avatar for Test')
  a.process('[Behaviour] Switching Test to avatar First')
  a.process('[Behaviour] Switching Test to avatar First')
  a.process('[Behaviour] Switching Test to avatar Second')
  assert.equal(a.events.length, 2)
  assert.match(a.events[0].detail, /Loaded/)
  assert.match(a.events[1].detail, /Changed/)
  a.process('unrelated Switching Test to avatar Third')
  assert.equal(a.events.length, 2)
})
test('activity supports Unicode portal creators, world changes and bounded defensive snapshots', () => {
  const a = new ActivityEvents()
  a.process('[Behaviour] 狐さん has dropped a portal.')
  a.process('[Behaviour] Joining or Creating Room: Test World')
  a.process('[Behaviour] OnLeftRoom')
  assert.deepEqual(a.events.map(e => e.kind), ['portal', 'world', 'world'])
  assert.equal(a.events[0].name, '狐さん')
  for (let i = 0; i < 100; i++) a.add('join', String(i))
  assert.equal(a.events.length, 50)
  const snapshot = a.snapshot(); snapshot[0].name = 'changed'
  assert.notEqual(a.events[0].name, 'changed')
})

test('current PortalManager format emits activity without inventing creator or placement confirmation', () => {
  const { parsePortalEvent } = require('../modules/vrchat/world/activityEvents')
  const line = '2026.11.02 15:14:36 Debug      -  [PortalManager] Pending portal request fulfilled.'
  const activity = new ActivityEvents()
  activity.process(line)
  assert.equal(activity.events.length, 1)
  assert.equal(activity.events[0].kind, 'portal')
  assert.equal(activity.events[0].name, 'Portal')
  assert.equal(activity.events[0].detail, 'Portal request completed')
  assert.equal(parsePortalEvent(line).confirmedPlacement, false)
  for (const unrelated of ['Portal Mode: PlaceManually', '[API] Requesting Get inventory/spawn', '[PortalManager] Pending portal request failed.', '[Image Download] portals/world19.png']) assert.equal(parsePortalEvent(unrelated), null)
  activity.process(line)
  assert.equal(activity.events.length, 2)
  assert.ok(activity.events[1].id > activity.events[0].id)
})

test('portal destruction alerts do not claim placement or identify a player', () => {
  const { parsePortalEvent } = require('../modules/vrchat/world/activityEvents')
  const event = parsePortalEvent('[PortalManager] Received portal destroy event.')
  assert.equal(event.detail, 'Portal removed or expired')
  assert.equal(event.name, 'Portal')
  assert.equal(event.confirmedPlacement, false)
})
